  title: 'Portfolio Front End Developer Italy | Sofien Cheikh Mohamed',
  meta: [
    { name: 'description', content: 'Sofien Cheikh Mohamed, Front End Developer based in Bologna, Italy; creating interactive and responsive websites.' },
    { name: 'keywords', content: 'front end developer bologna, front end developer italy, web developer bologna, web developer italy' },
    { property: 'og:title', content: 'Front End Developer Bologna | Sofien Cheikh Mohamed' },
    { property: 'og:description', content: 'Experienced Front End Developer based in Bologna, Italy, specializing in responsive digital experiences.' }
  ]
})

onMounted(() => {
  const list = document.querySelectorAll<HTMLLIElement>('.list')
  const itemBox = document.querySelectorAll<HTMLElement>('.itemBox')

  list.forEach(listItem => {
    listItem.addEventListener('click', () => {
      list.forEach(li => li.classList.remove('active'))
      listItem.classList.add('active')

      const dataFilter = listItem.getAttribute('data-filter')

      itemBox.forEach(item => {
        item.classList.remove('active')
        item.classList.add('hide')

        if (dataFilter === 'all' || item.getAttribute('data-item') === dataFilter) {
          item.classList.remove('hide')
          item.classList.add('active')
        }
      })
    })
  })
})
</script>
